const axios = require('axios');

// GET /github/repos
const getUserRepos = async (req, res) => {
  try {
    const response = await axios.get('https://api.github.com/user/repos', {
      headers: {
        Authorization: `Bearer ${req.user.accessToken}`,
        Accept: 'application/vnd.github.mercy-preview+json',
      },
      params: { sort: 'updated', per_page: 20 },
    });
    res.json(response.data);
  } catch (err) {
    console.error('Error fetching repos:', err.message);
    res.status(500).json({ message: 'Failed to fetch repositories' });
  }
};

// GET /github/repos/:owner/:repo/pulls
const getRepoPulls = async (req, res) => {
  const { owner, repo } = req.params;
  try {
    const response = await axios.get(
      `https://api.github.com/repos/${owner}/${repo}/pulls`,
      {
        headers: {
          Authorization: `Bearer ${req.user.accessToken}`,
          Accept: 'application/vnd.github.v3+json',
        },
        params: { state: 'open', per_page: 30 },
      }
    );
    res.json(response.data);
  } catch (err) {
    console.error('Error fetching PRs:', err.message);
    res.status(500).json({ message: 'Failed to fetch pull requests' });
  }
};

// GET /github/repos/:owner/:repo/pulls/:pull_number/files
